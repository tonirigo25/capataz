import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const schemaPath = path.join(root, "prisma", "schema.prisma");
const outputDirectory = path.join(root, "docs", "architecture", "generated");
const schema = await readFile(schemaPath, "utf8");
const schemaHash = createHash("sha256").update(schema.replace(/\r\n/gu, "\n")).digest("hex");

const modelMatches = [...schema.matchAll(/^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm)];
const models = modelMatches.map((match) => {
  const fields = match[2].split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("//") && !line.startsWith("@@"))
    .map((line) => {
      const [name, type] = line.split(/\s+/, 3);
      return { name, type, attributes: line.slice(name.length + type.length + 2).trim() };
    });
  return { name: match[1], fields };
});
const modelNames = new Set(models.map((model) => model.name));
const scalarTypes = new Set(["String", "Int", "BigInt", "Float", "Decimal", "Boolean", "DateTime", "Json", "Bytes"]);

function baseType(type) {
  return type.replace(/[?\[\]]/g, "");
}

const relations = [];
for (const model of models) {
  for (const field of model.fields) {
    const target = baseType(field.type);
    if (modelNames.has(target) && !scalarTypes.has(target) && model.name < target) {
      relations.push([model.name, target]);
    }
  }
}

const dictionary = [
  "# Data dictionary",
  "",
  `Generated from \`prisma/schema.prisma\` (SHA-256 \`${schemaHash}\`). Do not edit this file manually.`,
  "",
  `Models: ${models.length}. Relations: ${relations.length}.`,
  "",
];
for (const model of models) {
  dictionary.push(`## ${model.name}`, "", "| Field | Prisma type | Constraints |", "| --- | --- | --- |");
  for (const field of model.fields) {
    dictionary.push(`| \`${field.name}\` | \`${field.type}\` | ${field.attributes ? `\`${field.attributes.replaceAll("|", "\\|")}\`` : "—"} |`);
  }
  dictionary.push("");
}

const erd = [
  "%% Generated from prisma/schema.prisma. Do not edit.",
  "erDiagram",
];
for (const model of models) {
  erd.push(`  ${model.name} {`);
  for (const field of model.fields.filter((field) => !modelNames.has(baseType(field.type))).slice(0, 16)) {
    const mermaidType = baseType(field.type).replace(/[^A-Za-z0-9_]/g, "_");
    erd.push(`    ${mermaidType} ${field.name}`);
  }
  erd.push("  }");
}
for (const [left, right] of relations) erd.push(`  ${left} }o--o{ ${right} : relates`);

const groups = [
  ["Platform", ["FeatureFlag", "IdempotencyRecord", "WebhookEvent", "IntegrationConnection", "EncryptedCredential"]],
  ["Fiscal", ["FiscalDocument", "FiscalRecord", "FiscalTransmission", "FiscalEvent", "FiscalSoftwareDeclaration"]],
  ["E-invoice and billing", ["ElectronicInvoiceArtifact", "ElectronicInvoiceDelivery", "ElectronicInvoiceStatusEvent", "BillingCustomer", "BillingPriceMapping", "BillingEvent"]],
  ["Delivery and privacy", ["EmailSuppression", "EmailWebhookEvent", "LegalDocumentVersion", "LegalAcceptance", "ProcessingActivity", "RetentionPolicy", "PrivacyRequest", "ConsentRecord", "DataBreachIncident"]],
  ["AI and product", ["CompanyAiPolicy", "AiModelVersion", "AiPromptVersion", "AiUsageEvent", "AiEvaluationRun", "AiGatewayOperation", "AiReviewEvent", "AiCircuitState", "ProductEvent", "CompanyDailyMetric", "PilotCohort", "PilotFeedback", "SupportTicket", "Incident"]],
  ["Private storage", ["StoredObject", "UploadScan", "Document"]],
];
const svgWidth = 1440;
const columnWidth = 220;
const startX = 30;
const rowHeight = 25;
const boxTop = 78;
const boxes = groups.map(([label, names], index) => {
  const x = startX + index * (columnWidth + 15);
  const height = 58 + names.length * rowHeight;
  const rows = names.map((name, row) => `<text x="${x + 14}" y="${boxTop + 54 + row * rowHeight}" class="model">${name}</text>`).join("");
  return `<g><rect x="${x}" y="${boxTop}" width="${columnWidth}" height="${height}" rx="12" class="box"/><text x="${x + 14}" y="${boxTop + 28}" class="group">${label}</text>${rows}</g>`;
}).join("");
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${svgWidth}" height="500" viewBox="0 0 ${svgWidth} 500" role="img" aria-labelledby="title desc"><title id="title">Orqena target schema ERD overview</title><desc id="desc">Generated overview of the additive readiness schema groups.</desc><style>.bg{fill:#f6fbfa}.box{fill:#fff;stroke:#087a68;stroke-width:2}.title{font:700 24px system-ui;fill:#073b34}.meta{font:14px system-ui;fill:#48645f}.group{font:700 15px system-ui;fill:#07594e}.model{font:12px ui-monospace,monospace;fill:#183a35}</style><rect class="bg" width="100%" height="100%"/><text id="title-text" x="30" y="36" class="title">Orqena target data model</text><text x="30" y="60" class="meta">Generated from Prisma · ${models.length} models · SHA-256 ${schemaHash.slice(0, 16)}…</text>${boxes}</svg>`;

await mkdir(outputDirectory, { recursive: true });
await Promise.all([
  writeFile(path.join(outputDirectory, "DATA_DICTIONARY.md"), `${dictionary.join("\n").trimEnd()}\n`, "utf8"),
  writeFile(path.join(outputDirectory, "ERD.mmd"), `${erd.join("\n")}\n`, "utf8"),
  writeFile(path.join(outputDirectory, "ERD.svg"), svg, "utf8"),
  writeFile(path.join(outputDirectory, "schema-manifest.json"), `${JSON.stringify({ schemaSha256: schemaHash, models: models.length, relations: relations.length, generatedFrom: "prisma/schema.prisma" }, null, 2)}\n`, "utf8"),
]);

console.log(JSON.stringify({ ok: true, models: models.length, relations: relations.length, schemaHash }));
